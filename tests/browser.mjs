import assert from 'node:assert/strict'
import { chromium, webkit } from 'playwright'
import { server } from '../scripts/serve.mjs'

server.listen(0, '127.0.0.1')
await new Promise((resolve) => server.once('listening', resolve))
const base = `http://127.0.0.1:${server.address().port}/spygame-pwa/`
const browser = await (process.env.BROWSER === 'webkit' ? webkit : chromium).launch({ headless: true })
try {
  for (const [width, height] of [[280, 653], [320, 568], [390, 844], [768, 1024], [1280, 900]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto(base)
    await page.getByRole('dialog', { name: /Keep Spy Pass/ }).waitFor()
    await page.getByRole('button', { name: 'Dismiss install popup' }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Install app', exact: true }).click()
    await page.getByRole('button', { name: 'Not now', exact: true }).click()
    await page.getByPlaceholder('Type a name').fill('Moon')
    await page.getByRole('button', { name: 'Add', exact: true }).click()
    await page.getByPlaceholder('Type a name').fill('Paris')
    await page.keyboard.press('Enter')
    await page.getByPlaceholder('Type a name').fill('Telescope')
    await page.keyboard.press('Enter')
    assert.equal(await page.locator('#name-list').textContent().then((text) => text.includes('Moon')), false)
    await page.getByRole('button', { name: 'Show names', exact: true }).click()
    assert.ok((await page.locator('#name-list').textContent()).includes('Moon'))
    await page.getByRole('button', { name: 'Hide names', exact: true }).click()
    await page.getByRole('button', { name: 'Deal to 3 players' }).click()
    assert.equal(await page.locator('#name-list').textContent(), '')
    for (let player = 1; player <= 3; player++) {
      await page.locator('#show-card-button').click()
      await page.locator('.secret').waitFor()
      assert.equal(await page.locator('#card').evaluate((el) => el.scrollWidth > el.clientWidth), false)
      await page.locator('#card').click()
      if (player < 3) assert.ok((await page.locator('#player-position').textContent()).includes(`Player ${player + 1}`))
    }
    await page.getByRole('heading', { name: 'Start talking.' }).waitFor()
    assert.equal(await page.locator('#name-answer').textContent(), '')
    await page.getByRole('button', { name: /Reveal the answer/ }).click()
    assert.ok(['Moon', 'Paris', 'Telescope'].includes(await page.locator('#name-answer').textContent()))
    await page.getByRole('button', { name: /Deal again with the same names/ }).click()
    await page.getByRole('button', { name: 'Quit', exact: true }).click()
    assert.equal(await page.locator('.name-row').count(), 3)
    assert.equal(await page.locator('.name-value.masked').count(), 3)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.evaluate(() => navigator.serviceWorker.ready)
    await page.waitForFunction(() => !!navigator.serviceWorker.controller)
    await page.context().setOffline(true)
    await page.reload()
    await page.getByRole('heading', { name: 'One name. One spy.' }).waitFor()
    assert.equal(await page.locator('.name-row').count(), 0, 'names are not persisted')
    assert.deepEqual(errors, [])
    console.log(`PASS ${width}×${height}: install dismissal, privacy, deal, reveal, hand-off, replay, quit, offline reload`)
    await page.close()
  }
  const page = await browser.newPage({ viewport: { width: 320, height: 568 }, reducedMotion: 'reduce' })
  await page.addInitScript(() => localStorage.setItem('spy-pass-install-dismissed-v1', 'yes'))
  await page.clock.install()
  await page.goto(base)
  await page.getByPlaceholder('Type a name').evaluate((input) => {
    const clipboardData = new DataTransfer()
    clipboardData.setData('text', 'A very very long secret with 40 letters!!,\nParis\nMoon')
    input.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
  })
  assert.equal(await page.locator('.name-row').count(), 3)
  await page.getByRole('button', { name: 'Deal to 3 players' }).click()
  await page.clock.fastForward(710)
  await page.locator('#card').click()
  await page.locator('.secret').waitFor()
  assert.equal(await page.locator('#countdown span').evaluate((el) => getComputedStyle(el).animationName), 'none')
  await page.clock.fastForward(3500)
  assert.equal(await page.locator('.secret').count(), 0, 'timer still hides with reduced motion')
  assert.ok((await page.locator('#player-position').textContent()).includes('Player 2'))
  assert.equal(await page.locator('#card').isDisabled(), true)
  await page.clock.fastForward(710)
  await page.locator('#card').click()
  await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide')))
  assert.equal(await page.locator('.secret').count(), 0, 'backgrounding removes the secret from the DOM')
  assert.ok((await page.locator('#player-position').textContent()).includes('Player 3'))
  await page.clock.fastForward(10000)
  assert.ok((await page.locator('#player-position').textContent()).includes('Player 3'), 'canceled timer cannot skip the next player')
  await page.close()
  console.log('PASS batch paste, timed auto-hide, hand-off lock, reduced motion, background concealment, stale timer cancellation')
  const ios = await browser.newPage({ viewport: { width: 390, height: 844 }, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 Version/17.0 Mobile/15E148 Safari/604.1', hasTouch: true, isMobile: true })
  await ios.goto(base)
  await ios.getByRole('button', { name: 'Install app', exact: true }).click()
  await ios.getByText('On iPhone or iPad:', { exact: false }).waitFor()
  await ios.getByRole('button', { name: 'Not now', exact: true }).click()
  assert.equal(await ios.evaluate(() => localStorage.getItem('spy-pass-install-dismissed-v1')), 'yes')
  await ios.close()
  console.log('PASS iPhone Add to Home Screen instructions and remembered dismissal')
} finally {
  await browser.close()
  await new Promise((resolve) => server.close(resolve))
}
